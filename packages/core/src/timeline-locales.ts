const zhSidebar: NonNullable<JanttOptions["translateTaskSidebar"]> = key => sidebar[key];
const zhToolbar: NonNullable<JanttOptions["translateToolbar"]> = key => toolbar[key];

const presets = {
  en: { labels: { locale: "en" }, translateToolbar: undefined, translateTaskSidebar: undefined },
  "zh-CN": { labels: zhTimeline, translateToolbar: zhToolbar, translateTaskSidebar: zhSidebar }
};

/** Returns the supported chart language, falling back to English. */
export function normalizeTimelineLocale(value: unknown): "en" | "zh-CN" {
  const locale = typeof value === "string" ? value.trim().toLowerCase() : "";
  return locale === "zh" || locale === "zh-cn" || locale === "zh-hans" || locale.startsWith("zh-hans-") ? "zh-CN" : "en";
}

/** Built-in text for a chart. Omit the locale to keep the engine's original defaults. */
export function getTimelineLocaleOptions(value: string | undefined): Pick<JanttOptions, "labels" | "translateToolbar" | "translateTaskSidebar"> {
  return value === undefined ? {} : presets[normalizeTimelineLocale(value)];
}
